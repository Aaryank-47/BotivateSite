/** Seed every table. `insert(table, rows)` must return the inserted rows (with ids). */
export function buildSeed(insert) {
  const userRows = insert("users", buildUsersData());
  const userIdByUsername = Object.fromEntries(userRows.map((u) => [u.username, u.id]));
  const companyIdByName = Object.fromEntries(
    userRows.filter((u) => u.role === "company").map((u) => [u.company_name || u.name, u.id])
  );
  const systemRows = insert("systems", buildSystemsData(companyIdByName));
  const systemIdByName = Object.fromEntries(systemRows.map((s) => [s.name, s.id]));
  const teamRows = insert("teams", buildTeamsData(userIdByUsername));
  const teamIdByName = Object.fromEntries(teamRows.map((t) => [t.name, t.id]));
  insert("team_members", buildTeamMembersData(teamIdByName, userIdByUsername));
  insert("cmp_task", buildCmpTaskData({ companyIdByName, systemIdByName, userIdByUsername }));
  insert("user_tasks", buildUserTasksData({ companyIdByName, systemIdByName, userIdByUsername }));
  insert("holidays", buildHolidaysData(userIdByUsername));
  insert("delegated_tasks", buildDelegatedTasksData(userIdByUsername));
  insert("checklist_tasks", buildChecklistTasksData(userIdByUsername));
  insert("weekly_calls", buildWeeklyCallsData(userIdByUsername));
  insert("orders", buildOrdersData(userIdByUsername, companyIdByName));
}
