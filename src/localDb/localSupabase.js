// ============================================================================
// localSupabase.js — a localStorage-backed stand-in for the supabase-js client.
// Implements just the query-builder surface this app uses:
//   from(table).select(cols, {count, head}) / insert / update / delete
//   .eq .neq .in .not .is .gt .gte .lt .lte .order .range .limit .single .maybeSingle
//   embedded selects:  alias:table!fk_name ( cols ),  table ( cols ),  child_table ( cols )
//   storage.from(bucket).upload / getPublicUrl   (files kept as data URLs)
// Data lives in localStorage under DB_KEY and is seeded with demo data on first run.
// ============================================================================
import { buildSeed } from "./seedData";

const DB_KEY = "botivate_localdb_v1";
const FILES_KEY = "botivate_localfiles_v1";

// ── persistence ─────────────────────────────────────────────────────────────
let db = null;

const persist = () => {
  try {
    localStorage.setItem(DB_KEY, JSON.stringify(db));
  } catch (e) {
    console.error("localDb: could not save (storage full?)", e);
  }
};

const nowIso = () => new Date().toISOString();
const pad5 = (n) => String(n).padStart(5, "0");

// column defaults mirroring the SQL schema (defaults + triggers)
const DEFAULTS = {
  users: () => ({ is_active: true, permission: {}, company_name: null }),
  systems: () => ({ environment: "original" }),
  teams: () => ({ is_active: true }),
  cmp_task: () => ({ status: "Open", priority: "Medium", given_date: nowIso() }),
  user_tasks: () => ({ status: "Pending", priority: "Medium", given_date: nowIso() }),
  holidays: () => ({}),
  delegated_tasks: () => ({}),
  checklist_tasks: () => ({}),
  weekly_calls: () => ({}),
  orders: () => ({ status: "Submitted", type_of_work: "Project", nda_required: false }),
};

const UNIQUE = { users: ["username"], user_tasks: ["task_no"], orders: ["serial_number"] };

const applyTriggers = (table, row) => {
  if (table === "user_tasks" && !row.task_no) row.task_no = `TASK-${pad5(row.id)}`;
  if (table === "orders" && !row.serial_number) row.serial_number = `ORD-${pad5(row.id)}`;
  return row;
};

const insertRows = (table, rows) => {
  const list = (db.tables[table] ||= []);
  const out = [];
  for (const input of rows) {
    const row = { ...(DEFAULTS[table]?.() || {}), ...input };
    for (const col of UNIQUE[table] || []) {
      if (row[col] != null && list.some((r) => String(r[col]) === String(row[col]))) {
        const err = new Error(`duplicate key value violates unique constraint on "${col}"`);
        err.code = "23505";
        throw err;
      }
    }
    db.seq[table] = (db.seq[table] || 0) + 1;
    row.id = row.id ?? db.seq[table];
    row.created_at = row.created_at || nowIso();
    row.updated_at = row.updated_at || row.created_at;
    applyTriggers(table, row);
    list.push(row);
    out.push(row);
  }
  return out;
};

const load = () => {
  if (db) return db;
  try {
    const raw = localStorage.getItem(DB_KEY);
    if (raw) {
      db = JSON.parse(raw);
      let changed = false;
      for (const sys of db.tables.systems || []) {
        if (String(sys.website_link || "").startsWith("https://demo.botivate.in/")) {
          sys.website_link = null;
          if (String(sys.system_username || "").startsWith("demo_")) sys.system_username = null;
          if (sys.system_password === "Demo@123") sys.system_password = null;
          changed = true;
        }
        // values auto-generated by an earlier version are removed; dummy columns stay blank until filled
        if (String(sys.dummy_link || "").startsWith("https://demo.botivate.in/")) {
          sys.dummy_link = null;
          if (String(sys.dummy_username || "").startsWith("demo_")) sys.dummy_username = null;
          if (sys.dummy_password === "Demo@123") sys.dummy_password = null;
          changed = true;
        }
      }
      if (changed) persist();
      return db;
    }
  } catch {
    /* fall through to seed */
  }
  db = { tables: {}, seq: {} };
  // first run: drop leftovers that referenced the old remote data ids
  ["botivate_task_overrides_v1", "botivate_local_tasks_v1", "botivate_task_testing_v1", "botivate_orders_v1"].forEach((k) => localStorage.removeItem(k));
  try {
    buildSeed((table, rows) => insertRows(table, rows));
  } catch (e) {
    console.error("localDb: seeding failed", e);
  }
  persist();
  return db;
};

/** Wipe all local data; it is re-seeded on the next load. */
export const resetLocalDb = () => {
  localStorage.removeItem(DB_KEY);
  localStorage.removeItem(FILES_KEY);
  db = null;
};

// ── select-string parsing (handles nested embeds) ───────────────────────────
const splitTop = (str) => {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (const ch of str) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur);
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) parts.push(cur);
  return parts.map((p) => p.trim()).filter(Boolean);
};

const parseSelect = (str = "*") =>
  splitTop(str).map((item) => {
    const open = item.indexOf("(");
    if (open === -1) return { col: item };
    let head = item.slice(0, open).trim();
    const inner = item.slice(open + 1, item.lastIndexOf(")"));
    let alias = null;
    if (head.includes(":")) [alias, head] = head.split(":").map((x) => x.trim());
    const [target, hint] = head.split("!");
    return { embed: target.trim(), hint: hint && hint !== "inner" ? hint.trim() : null, alias: alias || target.trim(), sub: parseSelect(inner) };
  });

const singular = (name) => name.replace(/s$/, "");
// one-to-many embeds that are not forward foreign keys
const REVERSE = { "teams.team_members": "team_id" };
// a hint naming the embedded table's own foreign key (e.g. task_testing -> task_subtasks!task_subtasks_source_testing_id_fkey)
const reverseFkOf = (table, c) =>
  c.hint && !c.hint.startsWith(`${table}_`) && c.hint.startsWith(`${c.embed}_`)
    ? c.hint.slice(c.embed.length + 1).replace(/_fkey$/, "")
    : null;

const project = (table, row, cols) => {
  const out = {};
  for (const c of cols) {
    if (c.col === "*") Object.assign(out, row);
    else if (c.col) out[c.col] = row[c.col] === undefined ? null : row[c.col];
    else {
      const rev = REVERSE[`${table}.${c.embed}`] || reverseFkOf(table, c);
      const targetRows = load().tables[c.embed] || [];
      if (rev) {
        out[c.alias] = targetRows
          .filter((t) => String(t[rev]) === String(row.id))
          .map((t) => project(c.embed, t, c.sub));
      } else {
        let fk;
        if (c.hint) fk = c.hint.replace(new RegExp(`^${table}_`), "").replace(/_fkey$/, "");
        else fk = `${singular(c.embed)}_id`;
        const target = targetRows.find((t) => String(t.id) === String(row[fk]));
        out[c.alias] = target ? project(c.embed, target, c.sub) : null;
      }
    }
  }
  return out;
};

// ── filtering / ordering ────────────────────────────────────────────────────
const cmp = (a, b) => {
  if (a == null && b == null) return 0;
  if (a == null) return -1;
  if (b == null) return 1;
  const na = Number(a);
  const nb = Number(b);
  if (!Number.isNaN(na) && !Number.isNaN(nb)) return na - nb;
  const da = typeof a === "string" ? Date.parse(a) : NaN;
  const dbb = typeof b === "string" ? Date.parse(b) : NaN;
  if (!Number.isNaN(da) && !Number.isNaN(dbb)) return da - dbb;
  return String(a).localeCompare(String(b));
};

const parseList = (v) =>
  Array.isArray(v)
    ? v
    : String(v)
        .replace(/^\(|\)$/g, "")
        .split(",")
        .map((x) => x.trim().replace(/^"|"$/g, ""));

const PREDICATES = {
  eq: (a, v) => String(a) === String(v),
  neq: (a, v) => String(a) !== String(v),
  in: (a, v) => parseList(v).some((x) => String(x) === String(a)),
  is: (a, v) => (v === null ? a == null : a === v),
  gt: (a, v) => a != null && cmp(a, v) > 0,
  gte: (a, v) => a != null && cmp(a, v) >= 0,
  lt: (a, v) => a != null && cmp(a, v) < 0,
  lte: (a, v) => a != null && cmp(a, v) <= 0,
  like: (a, v) =>
    a != null &&
    new RegExp(`^${String(v).replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/%/g, ".*").replace(/_/g, ".")}$`).test(String(a)),
};

// ── query builder ───────────────────────────────────────────────────────────
class Query {
  constructor(table) {
    this.table = table;
    this.op = "select";
    this.filters = [];
    this.orders = [];
    this.selectStr = "*";
    this.returning = false;
    this.opts = {};
  }
  select(str = "*", opts = {}) {
    if (this.op === "select") {
      this.selectStr = str;
      this.opts = opts;
    } else {
      this.returning = true;
      this.selectStr = str;
    }
    return this;
  }
  insert(payload) { this.op = "insert"; this.payload = payload; return this; }
  update(payload) { this.op = "update"; this.payload = payload; return this; }
  delete() { this.op = "delete"; return this; }
  eq(c, v) { this.filters.push([c, "eq", v]); return this; }
  neq(c, v) { this.filters.push([c, "neq", v]); return this; }
  in(c, v) { this.filters.push([c, "in", v]); return this; }
  is(c, v) { this.filters.push([c, "is", v]); return this; }
  gt(c, v) { this.filters.push([c, "gt", v]); return this; }
  gte(c, v) { this.filters.push([c, "gte", v]); return this; }
  lt(c, v) { this.filters.push([c, "lt", v]); return this; }
  lte(c, v) { this.filters.push([c, "lte", v]); return this; }
  like(c, v) { this.filters.push([c, "like", v]); return this; }
  not(c, op, v) { this.filters.push([c, op, v, true]); return this; }
  order(c, { ascending = true } = {}) { this.orders.push([c, ascending]); return this; }
  range(from, to) { this.from = from; this.to = to; return this; }
  limit(n) { this.limitN = n; return this; }
  single() { this.mode = "single"; return this; }
  maybeSingle() { this.mode = "maybe"; return this; }

  matches(row) {
    return this.filters.every(([c, op, v, neg]) => {
      const ok = PREDICATES[op]?.(row[c], v) ?? true;
      return neg ? !ok : ok;
    });
  }

  run() {
    const d = load();
    const all = (d.tables[this.table] ||= []);
    let rows;
    let count = null;

    if (this.op === "insert") {
      const payload = Array.isArray(this.payload) ? this.payload : [this.payload];
      rows = insertRows(this.table, payload);
      persist();
    } else if (this.op === "update") {
      rows = all.filter((r) => this.matches(r));
      rows.forEach((r) => Object.assign(r, this.payload, { updated_at: nowIso() }));
      persist();
    } else if (this.op === "delete") {
      rows = all.filter((r) => this.matches(r));
      d.tables[this.table] = all.filter((r) => !rows.includes(r));
      if (this.table === "user_tasks") {
        (d.tables.cmp_task || []).forEach((t) => {
          if (rows.some((r) => String(r.id) === String(t.converted_task_id))) t.converted_task_id = null;
        });
      }
      persist();
    } else {
      rows = all.filter((r) => this.matches(r));
      count = rows.length;
      for (const [c, asc] of [...this.orders].reverse()) {
        rows = [...rows].sort((a, b) => (asc ? 1 : -1) * cmp(a[c], b[c]));
      }
      if (this.from != null) rows = rows.slice(this.from, this.to + 1);
      if (this.limitN != null) rows = rows.slice(0, this.limitN);
    }

    const returnsRows = this.op === "select" || this.returning;
    if (this.op === "select" && this.opts.head) return { data: null, error: null, count };
    if (!returnsRows) return { data: null, error: null, count };

    const cols = parseSelect(this.selectStr);
    const data = rows.map((r) => project(this.table, r, cols));

    if (this.mode) {
      if (data.length === 1) return { data: data[0], error: null, count };
      if (data.length === 0 && this.mode === "maybe") return { data: null, error: null, count };
      return {
        data: null,
        error: { code: "PGRST116", message: `JSON object requested, multiple (or no) rows returned (${data.length})` },
        count,
      };
    }
    return { data, error: null, count: this.opts.count ? count : null };
  }

  then(resolve, reject) {
    let result;
    try {
      result = this.run();
    } catch (err) {
      result = { data: null, error: { code: err.code, message: err.message }, count: null };
    }
    return Promise.resolve(result).then(resolve, reject);
  }
}

// ── storage (files kept as data URLs) ───────────────────────────────────────
const readFiles = () => {
  try {
    return JSON.parse(localStorage.getItem(FILES_KEY) || "{}");
  } catch {
    return {};
  }
};

const storage = {
  from: () => ({
    upload: async (name, file) => {
      try {
        const url = await new Promise((resolve, reject) => {
          const r = new FileReader();
          r.onload = () => resolve(r.result);
          r.onerror = reject;
          r.readAsDataURL(file);
        });
        const files = readFiles();
        files[name] = url;
        localStorage.setItem(FILES_KEY, JSON.stringify(files));
        return { data: { path: name }, error: null };
      } catch (e) {
        return { data: null, error: { message: e.message || "Could not store file locally" } };
      }
    },
    getPublicUrl: (name) => ({ data: { publicUrl: readFiles()[name] || "" } }),
  }),
};

