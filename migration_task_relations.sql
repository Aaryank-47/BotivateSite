-- Frontend/Backend testing split + task_relations (parent task -> rework task) +
-- transactional RPCs for every flow that writes to more than one row/table.
--
-- Run once in the Supabase SQL Editor. Safe to re-run (if not exists / or replace).
-- Each Postgres function runs as ONE transaction: if any statement inside fails,
-- everything it did is rolled back, so the app never ends up with half-saved data.
