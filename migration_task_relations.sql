-- ---------------------------------------------------------------------------
-- 1. task_testing: Frontend / Backend split
--    A delivery has Frontend and/or Backend rows, sharing delivery_group
--    (= id of the first row). Approval For Delivery needs all assigned rows Done.
-- ---------------------------------------------------------------------------
alter table public.task_testing
  add column if not exists tester_type text check (tester_type in ('Frontend', 'Backend')),
  add column if not exists delivery_group bigint,
  -- name of the logged-in member who saved the test result (Done / Issue); tested_at is when
  add column if not exists tested_by text;

create index if not exists task_testing_delivery_group_idx on public.task_testing (delivery_group);


-- ---------------------------------------------------------------------------
-- 2. task_relations: which task was created from which (rework / issue tasks)
--
--    parent_task_id    the task that was being tested/approved/informed (TASK-00047 or TASK-00047-1)
--    child_task_id     the rework task created for it                   (TASK-00047-2)
--    root_task_id      the original task at the top of the chain        (TASK-00047)
--    source_testing_id the task_testing row that raised it (its tester_type says Frontend/Backend)
--
--    This table is the single source of truth for these links; the old
--    task_testing.issue_task_id / approval_task_id / inform_task_id columns are no longer written.
-- ---------------------------------------------------------------------------
create table if not exists public.task_relations (
  id bigint generated by default as identity primary key,
  root_task_id bigint not null references public.user_tasks(id) on delete cascade,
  parent_task_id bigint not null references public.user_tasks(id) on delete cascade,
  child_task_id bigint not null references public.user_tasks(id) on delete cascade,
  source_testing_id bigint references public.task_testing(id) on delete set null,
  relation_type text not null
    check (relation_type in ('Testing Issue', 'Approval Not Done', 'Inform Not Done', 'DB Correction')),
  remarks text,
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint task_relations_unique unique (parent_task_id, child_task_id),
  constraint task_relations_not_self check (parent_task_id <> child_task_id)
);

create index if not exists task_relations_root_idx on public.task_relations (root_task_id);
create index if not exists task_relations_parent_idx on public.task_relations (parent_task_id);
create index if not exists task_relations_child_idx on public.task_relations (child_task_id);
create index if not exists task_relations_source_idx on public.task_relations (source_testing_id);

-- Same access as the other app tables (the app talks to Supabase with the anon key).
alter table public.task_relations disable row level security;
grant select, insert, update, delete on public.task_relations to anon, authenticated;


-- ---------------------------------------------------------------------------
-- 3. Backfill: links of rework tasks created before this migration
-- ---------------------------------------------------------------------------
insert into public.task_relations (root_task_id, parent_task_id, child_task_id, source_testing_id, relation_type)
select tt.task_id, tt.task_id, x.child_id, tt.id, x.kind
from public.task_testing tt
cross join lateral (
  values (tt.issue_task_id, 'Testing Issue'),
         (tt.approval_task_id, 'Approval Not Done'),
         (tt.inform_task_id, 'Inform Not Done'),
         (tt.db_task_id, 'DB Correction')
) as x(child_id, kind)
where tt.task_id is not null and x.child_id is not null and x.child_id <> tt.task_id
on conflict on constraint task_relations_unique do nothing;


-- ---------------------------------------------------------------------------
-- 4. View for filters / reports: every link with task numbers, statuses and
--    the Frontend/Backend side that raised it — no joins needed in the app.
-- ---------------------------------------------------------------------------
create or replace view public.task_relations_full as
select
  r.*,
  root.task_no   as root_task_no,
  parent.task_no as parent_task_no,
  child.task_no  as child_task_no,
  child.status   as child_status,
  tt.tester_type as source_tester_type,
  case when tt.tester_type is not null
       then parent.task_no || '-' || left(tt.tester_type, 1) end as source_testing_no
from public.task_relations r
join public.user_tasks root   on root.id = r.root_task_id
join public.user_tasks parent on parent.id = r.parent_task_id
join public.user_tasks child  on child.id = r.child_task_id
left join public.task_testing tt on tt.id = r.source_testing_id;

grant select on public.task_relations_full to anon, authenticated;


-- ---------------------------------------------------------------------------
-- 5. RPC: Task Update -> Complete
--    user_tasks -> Completed  +  new task_testing row (queued for Assign Tester)
--    If the task was created from a testing issue, the new row automatically
--    inherits tester_type and delivery_group from that issue's test row.
-- ---------------------------------------------------------------------------
create or replace function public.complete_task_with_delivery(
  p_task_id bigint,
  p_system_link text default null,
  p_github_link text default null,
  p_login_id text default null,
  p_password text default null,
  p_remarks text default null,
  p_made_by bigint default null,
  p_company_id bigint default null,
  p_system_id bigint default null,
  p_type_of_product text default null
) returns bigint
language plpgsql as $$
declare
  v_testing_id bigint;
  v_tester_type text;
  v_delivery_group bigint;
begin
  update public.user_tasks
     set status = 'Completed',
         completed_at = now(),
         updated_at = now(),
         link_of_system = coalesce(nullif(p_system_link, ''), link_of_system),
         github_link = coalesce(nullif(p_github_link, ''), github_link),
         remarks = coalesce(nullif(p_remarks, ''), remarks)
   where id = p_task_id;
  if not found then
    raise exception 'Task % not found', p_task_id;
  end if;

  -- If this task was created from a testing issue, inherit its tester_type and delivery_group
  select tt.tester_type, coalesce(tt.delivery_group, tt.id)
    into v_tester_type, v_delivery_group
    from public.task_relations tr
    join public.task_testing tt on tt.id = tr.source_testing_id
   where tr.child_task_id = p_task_id
     and tr.relation_type = 'Testing Issue'
   limit 1;

  insert into public.task_testing (
    task_id, made_by, company_id, system_id, type_of_product, date_of_delivery,
    system_link, github_link, system_login_id, system_password,
    tester_type, delivery_group, test_status, created_at, updated_at
  ) values (
    p_task_id, p_made_by, p_company_id, p_system_id, p_type_of_product, now(),
    nullif(p_system_link, ''), nullif(p_github_link, ''), nullif(p_login_id, ''), nullif(p_password, ''),
    v_tester_type, v_delivery_group, 'Pending', now(), now()
  )
  returning id into v_testing_id;

  return v_testing_id;
end;
$$;


-- ---------------------------------------------------------------------------
-- 6. RPC: Assign Tester
--    Assign Frontend and/or Backend tester. If both testers are picked, a second
--    row is created in the same transaction. Either one or both can be selected.
-- ---------------------------------------------------------------------------
create or replace function public.assign_testers(
  p_testing_id bigint,
  p_frontend_tester_id bigint default null,
  p_backend_tester_id bigint default null,
  p_expected_date timestamptz default null,
  p_remarks text default null,
  p_assigned_by bigint default null
) returns void
language plpgsql as $$
declare
  r public.task_testing%rowtype;
  v_type text;
  v_other text;
  v_tester bigint;
  v_other_tester bigint;
begin
  -- lock the row so two people assigning at once cannot both split it
  select * into r from public.task_testing where id = p_testing_id for update;
  if not found then
    raise exception 'Testing row % not found', p_testing_id;
  end if;
  if r.tester_id is not null then
    raise exception 'A tester is already assigned to this row';
  end if;

  if p_frontend_tester_id is null and p_backend_tester_id is null then
    raise exception 'Select at least one tester';
  end if;

  if r.tester_type is not null then
    v_type := r.tester_type;
    v_tester := case v_type when 'Frontend' then p_frontend_tester_id else p_backend_tester_id end;
    if v_tester is null then
      raise exception 'Select the % tester', v_type;
    end if;

    update public.task_testing
       set tester_id = v_tester,
           delivery_group = coalesce(delivery_group, id),
           expected_testing_date = p_expected_date,
           assign_remarks = nullif(p_remarks, ''),
           assigned_by = p_assigned_by,
           assigned_at = now(),
           updated_at = now()
     where id = r.id;
  else
    v_type := case when p_frontend_tester_id is not null then 'Frontend' else 'Backend' end;
    v_tester := case v_type when 'Frontend' then p_frontend_tester_id else p_backend_tester_id end;

    update public.task_testing
       set tester_id = v_tester,
           tester_type = v_type,
           delivery_group = coalesce(delivery_group, id),
           expected_testing_date = p_expected_date,
           assign_remarks = nullif(p_remarks, ''),
           assigned_by = p_assigned_by,
           assigned_at = now(),
           updated_at = now()
     where id = r.id;

    v_other := case v_type when 'Frontend' then 'Backend' else 'Frontend' end;
    v_other_tester := case v_other when 'Frontend' then p_frontend_tester_id else p_backend_tester_id end;

    -- Only insert the second row if the other tester was also provided
    if v_other_tester is not null then
      insert into public.task_testing (
        task_id, made_by, company_id, system_id, type_of_product, date_of_delivery,
        system_link, github_link, system_login_id, system_password,
        tester_type, delivery_group, test_status,
        tester_id, expected_testing_date, assign_remarks, assigned_by, assigned_at,
        created_at, updated_at
      ) values (
        r.task_id, r.made_by, r.company_id, r.system_id, r.type_of_product, r.date_of_delivery,
        r.system_link, r.github_link, r.system_login_id, r.system_password,
        v_other, coalesce(r.delivery_group, r.id), 'Pending',
        v_other_tester,
        p_expected_date,
        nullif(p_remarks, ''),
        p_assigned_by,
        now(),
        now(), now()
      );
    end if;
  end if;
end;
$$;


-- ---------------------------------------------------------------------------
-- 7. RPC: Tester / Approval For Delivery / Inform to Customer result
--    p_stage = 'test' | 'approval' | 'inform'
--    Failing status (test: Issue, approval/inform: Not Done) creates, in ONE transaction:
--      a) the rework task in user_tasks, numbered from the original task
--         (TASK-00047 -> TASK-00047-1, TASK-00047-2 ...),
--      b) its task_relations row,
--      c) the stage result on task_testing.
--    Returns the new rework task id (or null).
-- ---------------------------------------------------------------------------
create or replace function public.submit_stage_result(
  p_testing_id bigint,
  p_stage text,
  p_status text,
  p_remarks text default null,
  p_by_user_id bigint default null,
  p_by_name text default null
) returns bigint
language plpgsql as $$
declare
  r public.task_testing%rowtype;
  v_parent public.user_tasks%rowtype;
  v_root_id bigint;
  v_root_no text;
  v_next int;
  v_child_id bigint;
  v_fail text := case p_stage when 'test' then 'Issue' else 'Not Done' end;
  v_relation text := case p_stage when 'test' then 'Testing Issue'
                                  when 'approval' then 'Approval Not Done'
                                  else 'Inform Not Done' end;
  v_label text := case p_stage when 'test' then 'Testing issue'
                               when 'approval' then 'Delivery not approved'
                               else 'Customer not informed' end;
  v_source_no text;
  v_posted_by bigint;
  v_taken_from bigint;
  v_done_at timestamptz := case when p_status = 'Pending' then null else now() end;
  v_by_name text;
begin
  if p_stage not in ('test', 'approval', 'inform') then
    raise exception 'Unknown stage %', p_stage;
  end if;

  -- who marked it Done / raised the issue: the logged-in member (name from the app, else from users)
  v_by_name := coalesce(nullif(p_by_name, ''), (select u.name from public.users u where u.id = p_by_user_id));

  select * into r from public.task_testing where id = p_testing_id for update;
  if not found then
    raise exception 'Testing row % not found', p_testing_id;
  end if;

  if p_status = v_fail then
    select * into v_parent from public.user_tasks where id = r.task_id;
    if not found then
      raise exception 'Task % of this delivery not found', r.task_id;
    end if;

    -- root = top of the chain (a rework of a rework still counts under TASK-00047)
    select coalesce(
             (select tr.root_task_id from public.task_relations tr where tr.child_task_id = v_parent.id limit 1),
             v_parent.id)
      into v_root_id;
    select substring(task_no from '^TASK-[0-9]+') into v_root_no from public.user_tasks where id = v_root_id;
    v_root_no := coalesce(v_root_no, (select task_no from public.user_tasks where id = v_root_id));

    -- one numbering at a time per root task, so two issues never get the same number
    perform pg_advisory_xact_lock(v_root_id);
    select coalesce(max(substring(task_no from length(v_root_no) + 2)::int), 0) + 1
      into v_next
      from public.user_tasks
     where task_no like v_root_no || '-%'
       and substring(task_no from length(v_root_no) + 2) ~ '^[0-9]+$';

    v_source_no := case when p_stage = 'test' and r.tester_type is not null
                        then v_parent.task_no || '-' || left(r.tester_type, 1)
                        else v_parent.task_no end;

    v_posted_by := coalesce(p_by_user_id, 1);
    v_taken_from := r.made_by;
    if v_taken_from is null or v_taken_from = v_posted_by then
      v_taken_from := coalesce(r.company_id, case when v_posted_by = 1 then 2 else 1 end);
    end if;

    insert into public.user_tasks (
      task_no, given_date, posted_by, taken_from, company_id, system_id, type_of_work,
      expected_date_to_close, description_of_work, link_of_system, priority,
      assigned_member_1, assigned_by, assigned_at, status, is_testing_issue
    ) values (
      v_root_no || '-' || v_next, now(), v_posted_by, v_taken_from, r.company_id, r.system_id,
      (case p_stage when 'test' then 'Error Received' else 'Existing System Edit & Update' end)::public.work_type_enum,
      now() + interval '1 day',
      '[' || v_label || ' on DSP-' || lpad(coalesce(r.delivery_group, r.id)::text, 4, '0') || ' / ' || v_source_no || '] '
        || coalesce(p_remarks, ''),
      r.system_link, 'High'::public.priority_enum,
      r.made_by, v_posted_by, now(), 'In Progress'::public.task_status_enum, true
    )
    returning id into v_child_id;

    insert into public.task_relations (
      root_task_id, parent_task_id, child_task_id, source_testing_id, relation_type, remarks, created_by
    ) values (
      v_root_id, v_parent.id, v_child_id, r.id, v_relation, nullif(p_remarks, ''), p_by_user_id
    );
  end if;

  if p_stage = 'test' then
    update public.task_testing
       set test_status = p_status, tester_remarks = nullif(p_remarks, ''),
           tested_at = v_done_at, tested_by = v_by_name, updated_at = now()
     where id = r.id;
  elsif p_stage = 'approval' then
    update public.task_testing
       set approval_status = p_status, approval_remarks = nullif(p_remarks, ''),
           approval_checked_at = v_done_at, approval_checked_by = v_by_name, updated_at = now()
     where id = r.id
        or (r.delivery_group is not null and delivery_group = r.delivery_group);
  else
    update public.task_testing
       set inform_status = p_status, inform_remarks = nullif(p_remarks, ''),
           inform_checked_at = v_done_at, inform_checked_by = v_by_name, updated_at = now()
     where id = r.id
        or (r.delivery_group is not null and delivery_group = r.delivery_group);
  end if;

  return v_child_id;
end;
$$;

