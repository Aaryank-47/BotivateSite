-- ---------------------------------------------------------------------------
-- Holidays
-- Sundays are always non-working (handled in app logic, not stored here).
-- Used to auto-extend user_tasks / cmp_task expected_date_to_close so on-time metrics stay fair.
-- ---------------------------------------------------------------------------
create table public.holidays (
  id bigint generated by default as identity primary key,
  holiday_date date not null,
  name text not null,
  description text null,
  -- When true, same month/day is treated as holiday every year
  is_recurring boolean not null default false,
  created_by bigint null references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index idx_holidays_date_unique on public.holidays (holiday_date);
create index idx_holidays_recurring on public.holidays (is_recurring) where is_recurring = true;

-- ---------------------------------------------------------------------------
-- Delegated Tasks (internal task delegation for superadmin / admin / hod)
-- Spreadsheet columns:
--   Assign: Timestamp, Assigned By, Serial Number, Person Name, Task Details, Target Date
--   Auto: Planned Date, Actual Date (done), Delay Duration = Actual - Planned
--   Task done: Status, Remarks, New Target Date
-- ---------------------------------------------------------------------------
create sequence if not exists public.delegated_tasks_serial_seq start 1;

create table public.delegated_tasks (
  id bigserial primary key,
  serial_number text unique,
  assigned_by bigint not null references public.users(id) on delete cascade,
  assigned_to bigint not null references public.users(id) on delete cascade,
  task_details text not null,
  target_date date not null,
  planned_date date not null,
  actual_date date null,
  delay_duration integer null,
  status public.delegated_task_status not null default 'Pending',
  remarks text null,
  new_target_date date null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.generate_delegated_serial()
returns trigger language plpgsql as $$
begin
  if new.serial_number is null then
    new.serial_number := 'DLG-' || lpad(nextval('public.delegated_tasks_serial_seq')::text, 5, '0');
  end if;
  return new;
end;
$$;

create trigger set_delegated_serial before insert on public.delegated_tasks
  for each row when (new.serial_number is null)
  execute function public.generate_delegated_serial();

create index idx_delegated_tasks_assigned_to on public.delegated_tasks(assigned_to);
create index idx_delegated_tasks_assigned_by on public.delegated_tasks(assigned_by);
create index idx_delegated_tasks_status on public.delegated_tasks(status);
create index idx_delegated_tasks_target_date on public.delegated_tasks(target_date);

create sequence if not exists public.user_tasks_no_seq start 1;

create or replace function public.generate_task_no()
returns trigger language plpgsql as $$
begin
  if new.task_no is null then
    new.task_no := 'TASK-' || lpad(nextval('public.user_tasks_no_seq')::text, 5, '0');
