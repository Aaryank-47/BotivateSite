create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger set_task_no before insert on public.user_tasks
  for each row when (new.task_no is null)
  execute function public.generate_task_no();

